def crumbs(doc: Path, group: str, here: str) -> str:
    """Synapsa Commons > the map's group > this page: the way back to the map from any page."""
    up = rel(doc, ROOT / "README.md")
    mid = f" › [{group}]({up}#{group.lower()})" if group else ""
    return f"[Synapsa Commons]({up}){mid} › {here}"


