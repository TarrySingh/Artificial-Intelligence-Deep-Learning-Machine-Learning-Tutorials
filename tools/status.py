def artwork(check: bool) -> int:
    """The area tiles and icons the regions point at: present, current and within the rules."""
    import brand_svgs
    try:
        probs = brand_svgs.check() if check else brand_svgs.write()
    except brand_svgs.FontsUnavailable as e:
        # offline with an empty font cache: at least every file the regions point at must exist
        check = True
        probs = [f"missing  {p.relative_to(ROOT)}" for a in registry()[0] for kind in ("tile", "icon")
                 for theme in ("light", "dark")
                 if not (p := ROOT / "brand" / "areas" / f"{a['id'].lower()}-{kind}-{theme}.svg").exists()]
        print(f"  note        artwork not redrawn ({e}); checked that every area's files exist")
    for p in probs:
        what, name = p.split(None, 1)
        print(f"  STALE       {name}  ({what}; run: python tools/brand_svgs.py)" if check
              else f"  {what:<11} {name}")
    bad = brand_svgs.lint(quiet=True)
    if bad:
        print("  STALE       brand/ SVGs break the rules above (run: python tools/brand_svgs.py --lint)")
    return (len(probs) if check else 0) + (1 if bad else 0)


def main() -> int:
    check = "--check" in sys.argv
    every = [p for pat in LESSON_GLOBS for p in ROOT.glob(pat) if (p / "meta.yaml").exists()]
    if any(not (p / "tests" / "test_lesson.py").exists() for p in every):
        print("  these tables are regenerated in the maintainers' source, which holds the rubrics; "
              "nothing to do here")
        return 0
    stale = artwork(check)
    targets = [(p / "MODULES.md", programme_region(p)) for p in sorted(ROOT.glob("programmes/*/"))]
    readme = ROOT / "README.md"
    targets += [(readme, readme_region()), (readme, start_region()), (readme, paths_region()),
                (readme, anywhere_region()), (readme, compiled_region()), (readme, gates_region()), (readme, synapsa_region())]
    if release:
        targets.append((readme, coming_region()))
    targets += [(ROOT / "lessons" / "README.md", lessons_head_region()),
                (ROOT / "lessons" / "README.md", tracks_region())]
    for a in registry()[0]:
        if a["kind"] in ("programme", "flagship"):
            targets += [(ROOT / a["folder"] / "README.md", area_head_region(a)),
                        (ROOT / a["folder"] / "README.md", area_start_region(a))]
    pending = {}
    for path, region in targets:
        old = pending.get(path, path.read_text())
        name = re.match(r"<!-- (GEN:\w+|\w+)", region).group(1)
        rel_ = f"{path.relative_to(ROOT)} [{name}]"
        new = splice(old, region)
        if new is None:
            print(f"  NO MARKERS  {rel_}")
            stale += 1
        elif new == old:
            print(f"  current     {rel_}")
        elif check:
            print(f"  STALE       {rel_}  (run: python tools/status.py)")
            stale += 1
        else:
            pending[path] = new
            print(f"  updated     {rel_}")
    for path, text in pending.items():
        path.write_text(text)
    for path in course_docs():
        old, new = splice_notice(path)
        rel_ = path.relative_to(ROOT)
        if new == old:
            print(f"  current     {rel_} (notice)")
        elif check:
            print(f"  STALE       {rel_}  (licence notice missing or edited; run: python tools/status.py)")
            stale += 1
        else:
            path.write_text(new)
            print(f"  updated     {rel_} (notice)")
    return 1 if (check and stale) else 0


if __name__ == "__main__":
    raise SystemExit(main())
