def tracks_region() -> str:
    doc = ROOT / "lessons" / "README.md"
    areas, _, paths = registry()
    tracks = [a for a in areas if a["kind"] == "track"]
    steps = path_lessons(paths)
    lines = ["New here? Take [the beginner path](#start-from-zero), or pick a track." if steps
             else "Pick a track.", "", *tile_grid(doc, tracks)]
    if steps:
        lines += ["", "## Start from zero", "",
                  "Begin with some Python and take these in order"
                  + ("; each needs only the lessons before it." if in_order(steps) else "."), ""]
        for i, c in enumerate(steps, 1):
            lines += lesson_item(doc, c, f"{i}. ")
    for a in tracks:
        n = len(a["lessons"])
        # the icon sits in the line below the heading, never in it: an image in a heading puts a
        # dash in its anchor, which every tile links to
        icon = picture(doc, ROOT / "brand" / "areas" / f"{a['id'].lower()}-icon-light.svg", "", 40, 40, "middle")
        lines += ["", f"## {a['name']}", "", f"{icon} **{n} lesson{'s' if n != 1 else ''}**", "",
                  a["pitch"], ""]
        for d in a["lessons"]:
            lines += lesson_item(doc, card(d), "- ")
    return gen("tracks", lines)


